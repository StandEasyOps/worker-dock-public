# Fill ProductCode + InstallerSha256 from a built MSI, assert per-machine
# UpgradeCode, and prove silent msiexec /qn install + uninstall.
# Does not sign, publish, or submit to winget-pkgs.
param(
    [Parameter(Mandatory = $true)][string]$MsiPath,
    [Parameter(Mandatory = $true)][string]$ManifestDir,
    [Parameter(Mandatory = $true)][string]$OutDir,
    [string]$ExpectedUpgradeCode = "{33446F2E-DAB1-5268-912F-3F5D1835AF9C}",
    [string]$ExpectedVersion = ""
)

$ErrorActionPreference = "Stop"
$msi = (Resolve-Path $MsiPath).Path
$manifestDir = (Resolve-Path $ManifestDir).Path
New-Item -ItemType Directory -Force -Path $OutDir | Out-Null

$windowsInstaller = New-Object -ComObject WindowsInstaller.Installer
$db = $windowsInstaller.OpenDatabase($msi, 0)

function Get-MsiProperty {
    param($Database, [string]$Name)
    $query = "SELECT ``Value`` FROM ``Property`` WHERE ``Property``='$Name'"
    $view = $Database.OpenView($query)
    $view.Execute() | Out-Null
    $record = $view.Fetch()
    if (-not $record) { throw "MSI property $Name not found" }
    return $record.StringData(1)
}

$productCode = Get-MsiProperty $db "ProductCode"
$upgradeCode = Get-MsiProperty $db "UpgradeCode"
$allUsers = Get-MsiProperty $db "ALLUSERS"
$productName = Get-MsiProperty $db "ProductName"
$productVersion = Get-MsiProperty $db "ProductVersion"
$msiName = [System.IO.Path]::GetFileName($msi)

Write-Host "ProductName=$productName"
Write-Host "ProductVersion=$productVersion"
Write-Host "ProductCode=$productCode"
Write-Host "UpgradeCode=$upgradeCode"
Write-Host "ALLUSERS=$allUsers"

if ($productVersion -notmatch '^\d+\.\d+\.\d+$') {
    throw "ProductVersion $productVersion is not major.minor.build"
}
$fields = $productVersion.Split('.') | ForEach-Object { [int]$_ }
if ($fields | Where-Object { $_ -gt 65535 }) {
    throw "ProductVersion $productVersion has a field greater than 65535"
}
if ($ExpectedVersion -and $productVersion -ne $ExpectedVersion) {
    throw "ProductVersion $productVersion does not match expected $ExpectedVersion"
}

if ($allUsers -ne "1") {
    throw "MSI must be per-machine (ALLUSERS=1). Got ALLUSERS=$allUsers"
}
if ($upgradeCode.ToUpper() -ne $ExpectedUpgradeCode.ToUpper()) {
    throw "UpgradeCode $upgradeCode does not match pinned $ExpectedUpgradeCode"
}
if ($productName -ne "worker-dock") {
    throw "MSI ProductName must be worker-dock. Got $productName"
}
if ($msiName -notmatch '^worker-dock_') {
    throw "MSI filename must stay worker-dock_*.msi. Got $msiName"
}

$logInstall = Join-Path $env:TEMP "worker-dock-msiexec-install.log"
$logUninstall = Join-Path $env:TEMP "worker-dock-msiexec-uninstall.log"
Write-Host "Silent install: msiexec /i ... /qn /norestart"
$install = Start-Process -FilePath msiexec.exe -ArgumentList @("/i", $msi, "/qn", "/norestart", "/l*v", $logInstall) -Wait -PassThru
if ($install.ExitCode -notin 0, 1641, 3010) {
    if (Test-Path $logInstall) { Get-Content $logInstall -Tail 80 }
    throw "Silent install failed with exit $($install.ExitCode)"
}

$arp = @(
    "HKLM:\Software\Microsoft\Windows\CurrentVersion\Uninstall\*",
    "HKLM:\Software\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall\*"
) | ForEach-Object {
    Get-ItemProperty $_ -ErrorAction SilentlyContinue
} | Where-Object { $_.DisplayName -eq "worker-dock" -or $_.PSChildName -eq $productCode }

if (-not $arp) {
    throw "worker-dock is not in ARP after msiexec /qn install"
}
Write-Host "Silent install registered worker-dock"

Write-Host "Silent uninstall: msiexec /x ... /qn /norestart"
$uninstall = Start-Process -FilePath msiexec.exe -ArgumentList @("/x", $msi, "/qn", "/norestart", "/l*v", $logUninstall) -Wait -PassThru
if ($uninstall.ExitCode -notin 0, 1641, 3010) {
    if (Test-Path $logUninstall) { Get-Content $logUninstall -Tail 80 }
    throw "Silent uninstall failed with exit $($uninstall.ExitCode)"
}
Write-Host "Silent uninstall succeeded"

$hash = (Get-FileHash -Algorithm SHA256 -Path $msi).Hash.ToUpper()
$installerYaml = @"
# Generated by Packaging CI from the built MSI. Do not submit to winget-pkgs.
PackageIdentifier: StandEasyOps.WorkerDock
PackageVersion: $productVersion
InstallerLocale: en-US
Platform:
  - Windows.Desktop
MinimumOSVersion: 10.0.17763.0
InstallerType: wix
Scope: machine
InstallModes:
  - silent
  - silentWithProgress
  - interactive
InstallerSwitches:
  Silent: /qn /norestart
  SilentWithProgress: /qb /norestart
UpgradeBehavior: install
ElevationRequirement: elevationRequired
Dependencies:
  PackageDependencies:
    - PackageIdentifier: Microsoft.EdgeWebView2Runtime
Installers:
  - Architecture: x64
    InstallerUrl: https://get.standeasyops.com/releases/v$productVersion/$msiName
    InstallerSha256: "$hash"
    ProductCode: "$productCode"
    AppsAndFeaturesEntries:
      - DisplayName: worker-dock
        Publisher: Stand Easy Ops
        ProductCode: "$productCode"
        UpgradeCode: "$ExpectedUpgradeCode"
        InstallerType: wix
ManifestType: installer
ManifestVersion: 1.6.0
"@

function Set-CopiedPackageVersion {
    param([string]$Path, [string]$Version)
    $text = Get-Content -Raw -Path $Path
    $text = [regex]::Replace($text, '(?m)^PackageVersion:\s*\S+', "PackageVersion: $Version")
    Set-Content -Path $Path -Value $text -NoNewline
}

Copy-Item (Join-Path $manifestDir "StandEasyOps.WorkerDock.yaml") $OutDir
Copy-Item (Join-Path $manifestDir "StandEasyOps.WorkerDock.locale.en-US.yaml") $OutDir
Set-CopiedPackageVersion (Join-Path $OutDir "StandEasyOps.WorkerDock.yaml") $productVersion
Set-CopiedPackageVersion (Join-Path $OutDir "StandEasyOps.WorkerDock.locale.en-US.yaml") $productVersion
Set-Content -Path (Join-Path $OutDir "StandEasyOps.WorkerDock.installer.yaml") -Value $installerYaml -NoNewline
# Keep notes beside the MSI, not in $OutDir — winget validate scans that folder.
$notesDir = Split-Path -Parent (Resolve-Path $OutDir)
Set-Content -Path (Join-Path $notesDir "MSI-PROPERTIES.txt") -Value @"
Scope=machine
ALLUSERS=1
ProductVersion=$productVersion
ProductCode=$productCode
UpgradeCode=$ExpectedUpgradeCode
InstallerSha256=$hash
SilentInstall=msiexec /i $msiName /qn /norestart
SilentUninstall=msiexec /x $productCode /qn /norestart
"@

Write-Host "Wrote filled winget manifests to $OutDir"
Write-Host "Wrote MSI-PROPERTIES.txt to $notesDir"
Write-Host "InstallerSha256=$hash"
